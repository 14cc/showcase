#!/usr/bin/env python3
"""
Generate source/embedded_cert.h from certificate.p7b + identity.pk8.

The p7b (public certificate) is embedded verbatim. The 32-byte P-256 private
scalar is XORed with a SHA-256-derived keystream so it never appears in the
binary as plaintext (obfuscation, not real encryption — on a jailbroken device
a determined attacker can still recover it at runtime; this only keeps casual
`strings`/`otool`/memory-grep from finding it).

Usage: python3 gen_embedded_cert.py certificate.p7b identity.pk8 > source/embedded_cert.h
"""
import sys, os, hashlib
from cryptography.hazmat.primitives.serialization import load_der_private_key

def c_array(name, data):
    lines = [f"static const unsigned char {name}[] = {{"]
    for i in range(0, len(data), 12):
        chunk = data[i:i+12]
        lines.append("    " + "".join(f"0x{b:02x}, " for b in chunk).rstrip())
    lines.append("};")
    return "\n".join(lines)

def main():
    p7b = open(sys.argv[1], "rb").read()
    pk8 = open(sys.argv[2], "rb").read()

    key = load_der_private_key(pk8, password=None)
    d = key.private_numbers().private_value
    scalar = d.to_bytes(32, "big")

    # keystream = SHA256(salt) (32 bytes, exactly covers the scalar)
    salt = os.urandom(32)
    keystream = hashlib.sha256(salt).digest()
    enc = bytes(a ^ b for a, b in zip(scalar, keystream))

    out = []
    out.append("/* AUTO-GENERATED by tools/gen_embedded_cert.py — do not edit by hand. */")
    out.append("/* Embedded MFi certificate + obfuscated private scalar (option 1). */")
    out.append("#ifndef SHOWCASE_EMBEDDED_CERT_H")
    out.append("#define SHOWCASE_EMBEDDED_CERT_H")
    out.append("#define EMB_CERT_PRESENT 1")
    out.append(c_array("EMB_P7B", p7b))
    out.append(f"#define EMB_P7B_LEN {len(p7b)}")
    out.append(c_array("EMB_SALT", salt))
    out.append(c_array("EMB_SCALAR_ENC", enc))
    out.append("#endif /* SHOWCASE_EMBEDDED_CERT_H */")
    print("\n".join(out))

if __name__ == "__main__":
    main()
