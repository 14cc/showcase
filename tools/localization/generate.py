#!/usr/bin/env python3
"""Writes source/Localizations/<language>.lproj/Localizable.strings from translations.py."""
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from keys import keys  # noqa: E402
from translations import LANGUAGES, T  # noqa: E402

OUT = Path(__file__).resolve().parents[2] / 'source/Localizations'


def quote(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


def main():
    order = keys()
    missing = [k for k in order if k not in T]
    if missing:
        sys.exit('Missing translations:\n' + '\n'.join(map(repr, missing)))
    for index, language in enumerate(LANGUAGES):
        lines = ['/* Generated by tools/localization/generate.py from translations.py. */', '']
        lines += [f'{quote(k)} = {quote(T[k][index])};' for k in order]
        path = OUT / f'{language}.lproj/Localizable.strings'
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text('\n'.join(lines) + '\n', encoding='utf-8')
        print(path.relative_to(OUT.parents[1]))


if __name__ == '__main__':
    main()
